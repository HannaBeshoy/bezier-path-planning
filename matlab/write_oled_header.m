function write_oled_header(file, path, obstacles, world, n_points)
%WRITE_OLED_HEADER  Path and obstacles in OLED pixels, as a C header for the Arduino sketch.
%   write_oled_header(file, path, obstacles, world, n_points)
%   world = [width height] in metres, mapped onto the 128 x 64 display (y up in
%   the world, down on the display). The path is resampled to n_points points
%   evenly spaced along its length, so the animated car moves at constant speed.
sx = 127 / world(1); sy = 63 / world(2);
[~, ~, s] = curve_props(path.xy, path.d, path.dd);
q = linspace(0, s(end), n_points)';
[su, iu] = unique(s);
X = interp1(su, path.xy(iu, 1), q); Y = interp1(su, path.xy(iu, 2), q);
D = interp1(su, path.d(iu, :), q);
px = round(X * sx); py = round(63 - Y * sy);
ang = round(atan2(D(:, 2) * sy, D(:, 1) * sx) / (2 * pi) * 256);   % heading in world axes (y up), 256 steps per turn
ang = mod(ang, 256);
fid = fopen(file, 'w');
fprintf(fid, '// Generated by write_oled_header.m from run_all.m. Do not edit by hand.\n');
fprintf(fid, '// %d points along the path, evenly spaced; world %.2f m x %.2f m on 128 x 64 pixels.\n', n_points, world);
fprintf(fid, '#pragma once\n#include <avr/pgmspace.h>\n\n');
fprintf(fid, 'const uint8_t PATH_N = %d;\n', n_points);
fprintf(fid, 'const uint8_t PATH_X[PATH_N] PROGMEM = {%s};\n', join_nums(px));
fprintf(fid, 'const uint8_t PATH_Y[PATH_N] PROGMEM = {%s};\n', join_nums(py));
fprintf(fid, '// heading of the car at each point: 0 = right, 64 = up, 128 = left, 192 = down\n');
fprintf(fid, 'const uint8_t PATH_HEADING[PATH_N] PROGMEM = {%s};\n\n', join_nums(ang));
fprintf(fid, 'const uint8_t OBST_N = %d;\n', size(obstacles, 1));
fprintf(fid, '// x, y, radius in pixels\n');
fprintf(fid, 'const uint8_t OBST[OBST_N][3] PROGMEM = {%s};\n', ...
        strjoin(arrayfun(@(k) sprintf('{%d, %d, %d}', round(obstacles(k, 1) * sx), ...
        round(63 - obstacles(k, 2) * sy), max(1, round(obstacles(k, 3) * sx))), 1:size(obstacles, 1), ...
        'UniformOutput', false), ', '));
W = path.waypoints;
fprintf(fid, 'const uint8_t WAYPOINT_N = %d;\n', size(W, 1));
fprintf(fid, 'const uint8_t WAYPOINT[WAYPOINT_N][2] PROGMEM = {%s};\n', ...
        strjoin(arrayfun(@(k) sprintf('{%d, %d}', round(W(k, 1) * sx), round(63 - W(k, 2) * sy)), ...
        1:size(W, 1), 'UniformOutput', false), ', '));
fclose(fid);
end

function s = join_nums(v)
s = strjoin(arrayfun(@(x) sprintf('%d', x), v(:)', 'UniformOutput', false), ', ');
end
